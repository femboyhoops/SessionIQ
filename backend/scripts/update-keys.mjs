// Refreshes src/mojang-keys.ts from Mojang. Run on your own computer (Mojang blocks Cloudflare's network):
//   npm run update-keys && npm run deploy
import { writeFileSync } from "node:fs";

const res = await fetch("https://api.minecraftservices.com/publickeys");
if (!res.ok) {
	throw new Error(`Mojang answered ${res.status}`);
}
const { playerCertificateKeys } = await res.json();
if (!Array.isArray(playerCertificateKeys) || playerCertificateKeys.length === 0) {
	throw new Error("No playerCertificateKeys in the response");
}
const lines = playerCertificateKeys.map((k) => `\t"${k.publicKey}",`).join("\n");
writeFileSync(
	new URL("../src/mojang-keys.ts", import.meta.url),
	"// Generated by `npm run update-keys` from https://api.minecraftservices.com/publickeys (playerCertificateKeys).\n" +
		"// Mojang blocks that URL from Cloudflare's network, so the keys are bundled. They change very rarely.\n" +
		`export const PLAYER_CERTIFICATE_KEYS: string[] = [\n${lines}\n];\n`,
);
console.log(`Wrote ${playerCertificateKeys.length} keys to src/mojang-keys.ts`);
