	public static final int SIZE = 9;
	final int[][] runs;

	Icons(String... rows) {
		java.util.List<int[]> out = new java.util.ArrayList<>();
		for (int y = 0; y < rows.length; y++) {
			String r = rows[y];
			int x = 0;
			while (x < r.length()) {
				if (r.charAt(x) == '#') {
					int start = x;
					while (x < r.length() && r.charAt(x) == '#') {
						x++;
					}
					out.add(new int[]{y, start, x - start});
				} else {
					x++;
				}
			}
		}
		runs = out.toArray(new int[0][]);
	}
