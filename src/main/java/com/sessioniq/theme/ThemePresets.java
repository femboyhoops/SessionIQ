	private static Theme make(String name, boolean dark, int bg, int bg2, int surface, int surface2, int border, int text, int text2,
							  int accent, int success, int warning, int error, int[] chart, int radius) {
		Theme t = new Theme();
		t.name = name;
		t.builtIn = true;
		t.dark = dark;
		t.bg = bg;
		t.bg2 = bg2;
		t.surface = surface;
		t.surface2 = surface2;
		t.border = border;
		t.text = text;
		t.text2 = text2;
		t.accent = accent;
		t.success = success;
		t.warning = warning;
		t.error = error;
		t.chart = chart;
		t.radius = radius;
		t.panelOpacity = 1f;
		t.backdropOpacity = dark ? 0.94f : 0.97f;
		return t;
	}

	public static Theme base(boolean dark) {
		return all().get(dark ? 0 : 5);
	}
